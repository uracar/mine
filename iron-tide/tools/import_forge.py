#!/usr/bin/env python3
"""Pull every Shape Forge model from the modelling session's branch into js/models.js (one minified JSON object, FORGE_MODELS).
Usage (from iron-tide/):  python3 tools/import_forge.py [branch]      default branch: claude/keen-planck-pp8ipf
Then map new models to Service Tree nodes in FORGE_USE (game.js, search 'const FORGE_USE'). Trees are picked up by name (iron-tide-tree-*)."""
import json, pathlib, subprocess, sys
root = pathlib.Path(__file__).resolve().parent.parent
branch = sys.argv[1] if len(sys.argv) > 1 else 'claude/keen-planck-pp8ipf'
git = lambda *a: subprocess.run(['git', '-C', str(root), *a], check=True, capture_output=True, text=True).stdout
git('fetch', '-q', 'origin', branch)
print('source', git('log', '--oneline', '-1', 'FETCH_HEAD').strip())
def rnd(o):
    if isinstance(o, float):
        r = round(o, 4); return int(r) if r == int(r) else r
    if isinstance(o, list): return [rnd(x) for x in o]
    if isinstance(o, dict): return {k: rnd(v) for k, v in o.items()}
    return o
out = {}
for f in git('ls-tree', '--full-tree', '--name-only', 'FETCH_HEAD', 'shape-forge/models/').split():
    if not f.endswith('.json'): continue
    m = json.loads(git('show', 'FETCH_HEAD:' + f))
    if isinstance(m.get('model'), str): m = json.loads(m['model'])
    out[pathlib.Path(f).stem] = rnd(m)
s = json.dumps(out, separators=(',', ':'))
assert '</script' not in s.lower()
(root / 'js' / 'models.js').write_text(
    "// v6.5 3D models made in Shape Forge (the Shelf), imported by forgeMesh() in game.js. Part list format: shape, size, position, rotation (degrees),\n"
    "// scale, colour, material, group; groups: moving parts with a pivot and an animation (turret, recoil, flash, roll, track, spin, blink, fold, flame, wiggle).\n"
    "// Generated by tools/import_forge.py - do not edit by hand.\nconst FORGE_MODELS=" + s + ";\n")
used = set(__import__('re').findall(r"'(iron-tide-[a-z0-9-]+)'", (root / 'js' / 'game.js').read_text()))
print(len(out), 'models,', len(s), 'bytes')
print('not yet mapped in FORGE_USE:', sorted(k for k in out if k not in used and not k.startswith('iron-tide-tree')) or 'none')
