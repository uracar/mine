#!/usr/bin/env python3
"""Regenerate brain/codemap.md: every section header and top-level function in the game's JS files, with line numbers.
Read the map instead of the 15k-line game.js, then open only the lines you need. Run after big edits:  python3 tools/codemap.py"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
out = ['# Code map (generated by tools/codemap.py - do not edit by hand)', '',
       'Line numbers drift as code changes: search for the quoted text, or rerun the script.', '']
SEC = re.compile(r'^\s*// (?:-{5,}|={5,})\s*(.*?)\s*(?:-{3,}|={3,})?\s*$')
FN = re.compile(r'^(?:async\s+)?function\s+([A-Za-z0-9_$]+)\s*\(|^(?:const|let|var)\s+([A-Za-z0-9_$]+)\s*=\s*(?:\([^)]*\)|[A-Za-z0-9_$]+)\s*=>')
CONST = re.compile(r'^const\s+([A-Z][A-Z0-9_]{2,})\s*=')
for f in ['js/game.js', 'js/shaders.js', 'js/terrain.js', 'js/boot.js']:
    lines = (root / f).read_text().split('\n')
    out += [f'## {f} ({len(lines)} lines)', '']
    fns = []
    def flush():
        if fns:
            out.append('  ' + ', '.join(fns)); fns.clear()
    for i, l in enumerate(lines, 1):
        m = SEC.match(l)
        if m and m.group(1):
            flush(); out.append(f'- **{i}** {m.group(1)[:110]}'); continue
        m = FN.match(l)
        if m:
            fns.append(f'{m.group(1) or m.group(2)}:{i}'); continue
        m = CONST.match(l)
        if m and f.endswith('.js'):
            fns.append(f'{m.group(1)}:{i}')
    flush(); out.append('')
(root / 'brain' / 'codemap.md').write_text('\n'.join(out) + '\n')
print('brain/codemap.md', sum(1 for _ in out), 'lines')
